#!/usr/bin/env python3
"""Belmonte props made for the game (not extracted from HarasValley): the owner's reference picture of each object,
then a Tripo image-to-model, Hidamari's model stage (tools/treehouse_props.py). Two stages, so the picture is
registered and checked before any credits are spent.

    uv run python games/yorimichi/tools/belmonte_props.py concept --image PATH [--only bench_armless]
    uv run python games/yorimichi/tools/belmonte_props.py model [--only ...] [--dry-run] [--approval "..."]
    uv run python games/yorimichi/tools/belmonte_props.py import --only SLUG --glb PATH [--views PICTURE ...]

Each prop lives in games/yorimichi/assets/belmonte/props/<slug>/: concept.jpg with provenance.json (who made the
picture and its hash), then job.json (the Tripo settings, task id and credits) and <slug>.glb, the model with its
texture made a 1024 JPEG. `import` takes a model the owner made in Tripo Studio instead (job.json records it,
with the pictures it was made from). The full-size pictures and the Tripo work folders stay in build/yorimichi/belmonte/props/.
The library's extracted models and source.json are never changed: world.belmonte fits each prop and places it where
the scene placed the model it replaces (world/regions/belmonte/props.py).
"""
import sys as _sys; from pathlib import Path as _Path; _sys.path.insert(0, str(_Path(__file__).resolve().parents[1] / 'world')); import yori  # noqa: E402
_sys.path.insert(0, str(_Path(__file__).resolve().parent))
import argparse, json
from pathlib import Path

from treehouse_art import compact, now, rel, sha

OUT = yori.ASSETS / 'belmonte' / 'props'
WORK = yori.OUT / 'belmonte' / 'props'
ORIGINALS, TRIPO = WORK / 'concepts', WORK / 'tripo'

# slug: (the object, as the picture shows it)
PROPS = {
    'bench_armless': 'an armless Tuscan town bench: four oak seat planks and two oak back boards on two green cast-iron '
                     'legs, a steel strip along the seat\'s front edge (its grind edge). The owner\'s decision '
                     '(2026-10-22): one real bench, used at every bench of Belmonte, instead of the extracted bench '
                     'with its armrests cut off',
}


def concept(slug, image):
    """Register the owner's picture as the prop's concept: the full-size original under build/, the compact copy and
    its provenance beside the model."""
    folder = OUT / slug; record = folder / 'provenance.json'
    data = Path(image).read_bytes()
    if record.exists() and json.loads(record.read_text())['concept_sha256'] == sha(data):
        print(slug, 'already registered', flush=True); return slug, None
    folder.mkdir(parents=True, exist_ok=True)
    original = ORIGINALS / slug / 'concept.png'; original.parent.mkdir(parents=True, exist_ok=True)
    original.write_bytes(data)
    record.write_text(json.dumps({
        'source': 'reference picture supplied by the project owner (not generated by this tool)',
        'file': Path(image).name, 'object': PROPS[slug], 'registered_at': now(), 'concept_sha256': sha(data),
        'compact_copy': compact(data, folder / 'concept.jpg', 'props'),
        'execution': 'games/yorimichi/tools/belmonte_props.py'}, indent=2) + '\n')
    print(slug, 'registered', rel(folder / 'concept.jpg'), flush=True)
    return slug, None


def model(slug, faces, approval, dry):
    import treehouse_props
    return treehouse_props.model(slug, faces, approval, dry, out=OUT, tripo=TRIPO, originals=ORIGINALS,
                                 stage='belmonte_prop', record='provenance.json')


def import_model(slug, glb, views):
    """A model the owner made in Tripo Studio from their own pictures: compacted like the model stage's, recorded in
    job.json with the hashes of what it was made from (file names only, never a local path)."""
    from atelier.gltf import compact_glb, glb_parts
    folder = OUT / slug
    if not (folder / 'provenance.json').exists():
        return slug, 'no concept: register the owner\'s picture first'
    data = Path(glb).read_bytes()
    doc, _ = glb_parts(data)
    (folder / f'{slug}.glb').write_bytes(compact_glb(data))
    (folder / 'job.json').write_text(json.dumps({
        'stage': 'belmonte_prop', 'slug': slug, 'made_by': 'the project owner, in Tripo Studio',
        'generator': doc.get('asset', {}).get('generator'), 'input': Path(glb).name, 'input_sha256': sha(data),
        'views': {Path(v).name: sha(Path(v).read_bytes()) for v in views}, 'imported_at': now(),
        'execution': 'games/yorimichi/tools/belmonte_props.py import'}, indent=2) + '\n')
    print(slug, 'model', rel(folder / f'{slug}.glb'), flush=True)
    return slug, None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('stage', choices=['concept', 'model', 'import'])
    ap.add_argument('--only', default=''); ap.add_argument('--dry-run', action='store_true')
    ap.add_argument('--image', help='concept: the owner\'s picture')
    ap.add_argument('--glb', help='import: the owner\'s model'); ap.add_argument('--views', nargs='*', default=[],
                                                                          help='import: the pictures it was made from')
    ap.add_argument('--faces', type=int, default=12000)
    ap.add_argument('--approval', default='pending', help='who approved spending the credits, kept in job.json')
    a = ap.parse_args()
    slugs = [s for s in PROPS if not a.only or s in a.only.split(',')]
    if a.stage == 'concept':
        if not a.image or len(slugs) != 1:
            ap.error('concept takes --image and one --only slug')
        results = [concept(slugs[0], a.image)]
    elif a.stage == 'import':
        if not a.glb or len(slugs) != 1:
            ap.error('import takes --glb and one --only slug')
        results = [import_model(slugs[0], a.glb, a.views)]
    else:
        results = [model(s, a.faces, a.approval, a.dry_run) for s in slugs]
    bad = [(s, e) for s, e in results if e]
    for s, e in bad: print('FAILED', s, e)
    raise SystemExit(1 if bad else 0)


if __name__ == '__main__':
    main()
